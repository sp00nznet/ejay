"""
gen_dispatch.py - Generate the runtime far-call dispatcher.

Indirect far calls/jumps (`call far [mem]`) target a (selector, offset) pair
read from memory at runtime. Selectors are normalized to NE segment indices, so
(selector, offset) maps directly to a lifted function segNNN_XXXX. This emits a
switch over all functions so the runtime can dispatch them.

Run after the sources exist: python tools/gen_dispatch.py
"""
import os
import re
import glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(SRC, '_dispatch.c')

DEF_RE = re.compile(r'^void (seg(\d+)_([0-9A-Fa-f]+))\(CPU \*cpu\)', re.M)


def main():
    funcs = []  # (key, name)
    seen = set()
    for path in glob.glob(os.path.join(SRC, '*.c')):
        if os.path.basename(path) == os.path.basename(OUT):
            continue
        text = open(path, encoding='utf-8', errors='replace').read()
        for name, seg, off in DEF_RE.findall(text):
            if name in seen:
                continue
            seen.add(name)
            key = (int(seg) << 16) | int(off, 16)
            funcs.append((key, name))

    funcs.sort()

    lines = [
        '/* _dispatch.c - Auto-generated by gen_dispatch.py */',
        '/* Runtime dispatcher for indirect calls/jumps (function pointers). */',
        '',
        '#include "segments.h"',
        '',
        '/* Returns 1 and runs the target (which performs its own RET/RETF) if the',
        ' * (selector,offset) names a known function, else 0 (no stack change). */',
        'static int dispatch_lookup(CPU *cpu, uint16_t seg, uint16_t off)',
        '{',
        '    uint32_t k = ((uint32_t)seg << 16) | off;',
        '    switch (k) {',
    ]
    for key, name in funcs:
        lines.append(f'    case 0x{key:08X}u: {name}(cpu); return 1;')
    lines += [
        '    default: return 0;',
        '    }',
        '}',
        '',
        '/* Far indirect call/jmp: on miss, clean up the 4-byte far frame. */',
        'void dispatch_far(CPU *cpu, uint16_t seg, uint16_t off)',
        '{',
        '    if (!dispatch_lookup(cpu, seg, off)) {',
        '#ifdef EJAY_TRACE_RUNTIME',
        '        fprintf(stderr, "dispatch_far MISS seg=%u off=%04X\\n", seg, off);',
        '#endif',
        '        cpu->sp += 4;',
        '    }',
        '}',
        '',
        '/* Near indirect call: on miss, clean up the 2-byte near frame. */',
        'void dispatch_near(CPU *cpu, uint16_t seg, uint16_t off)',
        '{',
        '    if (!dispatch_lookup(cpu, seg, off)) {',
        '#ifdef EJAY_TRACE_RUNTIME',
        '        fprintf(stderr, "dispatch_near MISS seg=%u off=%04X\\n", seg, off);',
        '#endif',
        '        cpu->sp += 2;',
        '    }',
        '}',
        '',
    ]

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {OUT}: dispatch over {len(funcs)} functions')


if __name__ == '__main__':
    main()
